"""Отсечение корпоративной email-подписи из входящих helpdesk-писем.

Подпись генерируется нашим сервисом ``app.services.signature.render_signature``
(см. ``backend/app/services/signature.py``): таблица с логотипом Mage_Ru.png +
ФИО/должность/телефоны/email в фирменных цветах (#00479D / #9E9E9E). Все письма
сотрудников интранет-портала (~300 чел.) приходят с этой подписью.

Без отсечения подпись попадает в ``helpdesk_messages.body_text`` и в MAX-
уведомление о новой заявке (заголовок «Заявка от ФИО» + «Текст заявки:»
засоряется блоком «Руководитель отдела / +7 ... / borzihin.vs@mage.ru»).

Подход — эвристика по стабильным маркерам подписи (мы авторы шаблона и точно
знаем структуру):

1. ``<img ... src=".../Mage_Ru.png" ...>`` — логотип. Самый надёжный маркер.
2. ``border(-right)?:solid #7B92AE`` — стиль ячейки-разделителя (логотип | текст).
3. ``color:#00479D`` / ``color: #00479D`` — фирменный синий ФИО.
4. ``mailto:...@mage.ru`` в ``<a>``, окружённом стилем подписи.

Каждый маркер ищется case-insensitive с допуском пробелов. От первого совпавшего
отрезается «хвост» — подпись всегда в конце письма. Если ни один не найден —
письмо возвращается как есть (идемпотентно).

Ограничения (осознанные):
- Подписи других почтовиков (Gmail/Яндекс/Thunderbird со своими шаблонами) не
  отрезаются — для интранета это редкость; такие подписи просто останутся в теле
  (как и до этого фикса).
- Ложное срабатывание: если во входящем письме случайно встретится ссылка на
  Mage_Ru.png или цвет #00479D вне подписи — отрежем лишнее. Нивелируется тем,
  что проверяем несколько маркеров: срабатывает «первый попавшийся», но сам
  маркер ищем в контексте подписи (логотип — это ``<img>``, цвет — в ``style=``).
- Подпись в середине текста (нетипично) отрежет и подпись, и текст после неё.
  На практике подпись всегда в конце, в т.ч. при ответах почтовик ставит подпись
  ниже ответа, но выше цитаты (а цитату уже снял ``strip_quoted_html``).

Слой 2 (маркер в самом шаблоне подписи, как ``REPLY_MARKER_TOKEN`` в
``email_quote``) — добавляется отдельно в ``render_signature``. Здесь — только
эвристика по маркерам (работает для всех существующих подписей, даже выпущенных
до потенциального будущего фикса генератора).
"""

from __future__ import annotations

import re

# Компилируем один раз при импорте (как ``_QUOTE_PATTERNS`` в ``email_quote``).

# 1. Логотип Mage_Ru.png (в любом регистре, любой путь до имени файла).
#    Outlook оборачивает ``src`` в кавычки/без, добавляет ``id=``, ``width=``,
#    ``height=`` — поэтому паттерн ищет только ``src=".../Mage_Ru.png"``.
_SIGNATURE_LOGO_RE = re.compile(
    r"""<img\b[^>]*\bsrc\s*=\s*["'][^"']*/?Mage_Ru\.png["']""",
    re.IGNORECASE,
)

# 2. Ячейка-разделитель с фирменным цветом границы ``solid #7B92AE``.
#    Outlook любит ``border-right:solid #7B92AE 1.0pt`` (без пробелов),
#    генератор — ``border-right: solid 1px #7B92AE`` (пробелы). Допускаем оба.
_SIGNATURE_BORDER_RE = re.compile(
    r"""border(?:-right|-left|-top|-bottom)?\s*:\s*solid\s+(?:\d+(?:\.\d+)?(?:px|pt)\s+)?#7[Bb]92[Aa][Ee]""",
    re.IGNORECASE,
)

# 3. Фирменный синий ФИО ``color:#00479D``. Outlook иногда вставляет ``;`` после,
#    генератор — без. Ищем в любом ``style="..."``.
_SIGNATURE_BLUE_RE = re.compile(r"""color\s*:\s*#00[47]79[Dd]""", re.IGNORECASE)

# 4. Mailto-ссылка на mage.ru — финальный маркер (email в подписи). Подпись
#    всегда заканчивается ``<a href="mailto:...@mage.ru">``.
_SIGNATURE_MAILTO_RE = re.compile(
    r"""<a\b[^>]*\bhref\s*=\s*["']mailto:[^"']*@(?:mage\.ru|portal-svc)["']""",
    re.IGNORECASE,
)

# Все паттерны в порядке «надёжность → вспомогательный».
_SIGNATURE_PATTERNS: tuple[re.Pattern[str], ...] = (
    _SIGNATURE_LOGO_RE,  # логотип — самый сильный маркер
    _SIGNATURE_BORDER_RE,  # цвет границы ячейки
    _SIGNATURE_BLUE_RE,  # фирменный синий
    _SIGNATURE_MAILTO_RE,  # mailto:@mage.ru
)


def strip_email_signature(html: str | None) -> str | None:
    """Отрезать корпоративную подпись из HTML-тела письма.

    Ищет первый совпавший маркер подписи (логотип Mage_Ru.png / цвет границы
    #7B92AE / синий #00479D / mailto:@mage.ru) и отрезает от него до конца
    строки (подпись всегда в конце письма).

    Возвращает обновлённый HTML или исходный, если подпись не найдена.
    ``None``/пустая строка → возвращаются как есть (идемпотентно).
    """
    if not html:
        return html
    for pattern in _SIGNATURE_PATTERNS:
        match = pattern.search(html)
        if match:
            # Отрезаем от начала совпавшего маркера до конца.
            # Trim trailing whitespace (подпись обычно отделяется ``<p>&nbsp;</p>``
            # и пустыми строками — оставляем минимальный хвост чистоты).
            return html[: match.start()].rstrip()
    return html
